const DICT: Record<string, Dict> = { en, de, fr, nl, es, it, hr, pl };
const KEY = 'va-lang';

function initial(): string {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && DICT[saved]) return saved;
  } catch { /* storage unavailable */ }
  const nav = (typeof navigator !== 'undefined' ? navigator.language : 'en').slice(0, 2).toLowerCase();
  return DICT[nav] ? nav : 'en';
}

type Ctx = { lang: string; setLang: (l: string) => void; t: (k: string) => string };
const I18n = createContext<Ctx>({ lang: 'en', setLang: () => {}, t: (k) => en[k] ?? k });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState(initial);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const setLang = useCallback((l: string) => {
    setLangState(l);
    try { localStorage.setItem(KEY, l); } catch { /* storage unavailable */ }
  }, []);
  const t = useCallback((k: string) => DICT[lang]?.[k] ?? en[k] ?? k, [lang]);
  return <I18n.Provider value={{ lang, setLang, t }}>{children}</I18n.Provider>;
}

export const useI18n = () => useContext(I18n);
export const useT = () => useContext(I18n).t;
/** Translated subject name, falling back to the name stored in the database. */
export function useSubjectName() {
  const { t, lang } = useContext(I18n);
  return useCallback((id: number, fallback: string) => {
    if (lang === 'en') return fallback;
    const v = t('subject.' + id);
    return v === 'subject.' + id ? fallback : v;
  }, [t, lang]);
}
